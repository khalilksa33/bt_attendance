def get_erp_attendance_data(start_date=None, end_date=None):
    if start_date is None or end_date is None:
        now = datetime.now()
        start_date = datetime(now.year, now.month, 1)
        end_date = now.replace(hour=23, minute=59, second=59, microsecond=999999)

    url = f"{erp_url}/api/resource/{ERP_ATTENDANCE_DOCTYPE}"
    headers = {'Authorization': f'token {api_key}:{os.getenv("ERP_API_SECRET")}', 'Content-Type': 'application/json'}
    filters = [
        [ERP_ATTENDANCE_DOCTYPE, ERP_ATTENDANCE_DATE_FIELD, ">=", start_date.strftime('%Y-%m-%d')],
        [ERP_ATTENDANCE_DOCTYPE, ERP_ATTENDANCE_DATE_FIELD, "<=", end_date.strftime('%Y-%m-%d')],
    ]
    params = {
        'fields': json.dumps([ERP_ATTENDANCE_EMPLOYEE_FIELD, ERP_ATTENDANCE_DATE_FIELD, ERP_ATTENDANCE_TIME_FIELD]),
        'filters': json.dumps(filters),
        'limit_page_length': 1000,
    }
    response = requests.get(url, headers=headers, params=params, timeout=30)
    if response.status_code == 417:
        # Some ERP installations block query access to the attendance_time field.
        fallback_params = params.copy()
        fallback_fields = [ERP_ATTENDANCE_EMPLOYEE_FIELD, ERP_ATTENDANCE_DATE_FIELD]
        fallback_params['fields'] = json.dumps(fallback_fields)
        response = requests.get(url, headers=headers, params=fallback_params, timeout=30)
    response.raise_for_status()
    data = response.json().get('data', [])

    attendance_records = []
    for item in data:
        employee = item.get(ERP_ATTENDANCE_EMPLOYEE_FIELD)
        date_value = item.get(ERP_ATTENDANCE_DATE_FIELD)
        time_value = item.get(ERP_ATTENDANCE_TIME_FIELD)

        if not employee or not date_value:
            continue

        timestamp_str = f"{date_value}T{time_value or '00:00:00'}"
        try:
            timestamp = datetime.fromisoformat(timestamp_str)
        except ValueError:
            try:
                timestamp = datetime.strptime(timestamp_str, '%Y-%m-%dT%H:%M:%S')
            except ValueError:
                continue

        attendance_records.append({'user_id': str(employee), 'timestamp': timestamp})

    return pd.DataFrame(attendance_records)


def push_checkin_to_erp(record):
    if not erp_url or not api_key:
        return False

    attendance_url = f"{erp_url}/api/resource/{ERP_ATTENDANCE_DOCTYPE}"
    headers = {'Authorization': f'token {api_key}:{os.getenv("ERP_API_SECRET")}', 'Content-Type': 'application/json'}
    timestamp = record.get('timestamp')
    if isinstance(timestamp, datetime):
        timestamp = timestamp.isoformat()

    date_part = timestamp.split('T')[0] if timestamp and 'T' in timestamp else datetime.now().strftime('%Y-%m-%d')
    time_part = timestamp.split('T')[1] if timestamp and 'T' in timestamp else datetime.now().strftime('%H:%M:%S')
    time_part = time_part[:8]

    payload = {
        ERP_ATTENDANCE_EMPLOYEE_FIELD: record.get('user_id'),
        ERP_ATTENDANCE_DATE_FIELD: date_part,
        ERP_ATTENDANCE_TIME_FIELD: time_part,
        'status': 'Present',
        'remarks': f"Check-in synced from biometric/portal at {timestamp}",
    }

    try:
        response = requests.post(attendance_url, headers=headers, json=payload, timeout=30)
        if response.ok:
            return True
        print(f"ERP check-in push failed: {response.status_code} {response.text}")
    except Exception as exc:
        print(f"ERP check-in push error: {exc}")
    return False


