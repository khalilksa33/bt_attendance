def get_remote_checkin_data(start_date=None, end_date=None):
    remote_source = os.getenv("REMOTE_CHECKIN_SOURCE")
    if not remote_source:
        return pd.DataFrame(columns=['user_id', 'timestamp'])

    try:
        if remote_source.lower().startswith("http"):
            headers = {'Authorization': f'token {api_key}:{os.getenv("ERP_API_SECRET")}' }
            response = requests.get(remote_source, headers=headers, timeout=10)
            response.raise_for_status()
            payload = response.json()
            data = payload.get('data', payload) if isinstance(payload, dict) else payload
            df = pd.DataFrame(data)
        elif remote_source.lower().endswith('.csv'):
            df = pd.read_csv(remote_source)
        elif remote_source.lower().endswith('.json'):
            df = pd.read_json(remote_source)
        else:
            raise ValueError("Unsupported REMOTE_CHECKIN_SOURCE format. Use HTTP, CSV, or JSON.")

        user_field = os.getenv('REMOTE_CHECKIN_USER_FIELD')
        if user_field and user_field in df.columns:
            df = df.rename(columns={user_field: 'user_id'})
        elif 'attendance_device_id' in df.columns:
            df = df.rename(columns={'attendance_device_id': 'user_id'})
        elif 'employee_id' in df.columns:
            df = df.rename(columns={'employee_id': 'user_id'})

        if 'timestamp' not in df.columns:
            raise ValueError("Remote checkin source must include a 'timestamp' column")

        df['timestamp'] = pd.to_datetime(df['timestamp'], errors='coerce')
        df = df.dropna(subset=['user_id', 'timestamp'])
        if start_date is not None and end_date is not None:
            df = df[(df['timestamp'] >= start_date) & (df['timestamp'] <= end_date)]
        df['user_id'] = df['user_id'].astype(str)
        return df[['user_id', 'timestamp']]
    except Exception as exc:
        print(f"Warning: failed to load remote checkins from {remote_source}: {exc}")
        return pd.DataFrame(columns=['user_id', 'timestamp'])


def write_id_log(df_bio, df_users, df_remote):
    log_dir = BASE_DIR / Path(os.getenv("LOG_DIR", "logs"))
    log_dir.mkdir(parents=True, exist_ok=True)
    log_path = log_dir / os.getenv("LOG_FILE", "attendance_ids.log")

    bio_ids = sorted(set(df_bio['user_id'].astype(str).unique()))
    # Filter out NaN values and convert to string
    erp_ids = sorted(set(str(id) for id in df_users['attendance_device_id'].dropna().unique()))
    remote_ids = sorted(set(df_remote['user_id'].astype(str).unique())) if not df_remote.empty else []

    matched_ids = sorted(set(bio_ids).intersection(erp_ids))
    biometric_only = sorted(set(bio_ids) - set(erp_ids))
    erp_only = sorted(set(erp_ids) - set(bio_ids))

    with open(log_path, 'a', encoding='utf-8') as log_file:
        log_file.write(f"\n===== Attendance ID Log: {datetime.now().isoformat()} =====\n")
        log_file.write(f"Biometric IDs ({len(bio_ids)}): {bio_ids}\n")
        log_file.write(f"ERP IDs ({len(erp_ids)}): {erp_ids}\n")
        if remote_ids:
            log_file.write(f"Remote check-in IDs ({len(remote_ids)}): {remote_ids}\n")
            remote_matched = sorted(set(remote_ids).intersection(erp_ids))
            remote_only = sorted(set(remote_ids) - set(erp_ids))
            log_file.write(f"Remote matched ERP IDs ({len(remote_matched)}): {remote_matched}\n")
            log_file.write(f"Remote-only IDs ({len(remote_only)}): {remote_only}\n")

        log_file.write(f"Matched IDs ({len(matched_ids)}): {matched_ids}\n")
        log_file.write(f"Biometric-only IDs ({len(biometric_only)}): {biometric_only}\n")
        log_file.write(f"ERP-only IDs ({len(erp_only)}): {erp_only}\n")
        log_file.write("====================================================\n")

    print(f"Attendance ID log written to: {log_path}")


def format_duration(start, end):
    if not isinstance(start, datetime) or not isinstance(end, datetime):
        return "N/A"
    duration = end - start
    if duration.total_seconds() < 0:
        return "N/A"
    hours = int(duration.total_seconds() // 3600)
    minutes = int((duration.total_seconds() % 3600) // 60)
    return f"{hours}h {minutes}m"


def write_daily_checkin_log(df_merged, df_users, report_start, report_end):
    exclude_names = {
        "CHAUHDRY MUHAMMAD ASLAM",
        "AHMAD HASAN MARJAN",
        "AHMED HASAN MARJAN",
        "ALJABRI ABDULELAH MAJED",
    }

    def normalize_name(value):
        return " ".join(str(value or "").upper().split())

    df_users = df_users.copy()
    df_users['attendance_device_id'] = df_users['attendance_device_id'].astype(str)
    df_merged = df_merged.copy()
    df_merged['attendance_device_id'] = df_merged['attendance_device_id'].astype(str)
    df_merged['timestamp'] = pd.to_datetime(df_merged['timestamp'], errors='coerce')
    df_merged = df_merged.dropna(subset=['timestamp'])
    df_merged['date'] = df_merged['timestamp'].dt.date

    rows = []
    for _, user in df_users.sort_values('attendance_device_id').iterrows():
        emp_id = str(user.get('attendance_device_id', '') or '').strip()
        if not emp_id:
            continue
        emp_name = (user.get('employee_name') or user.get('employee') or 'N/A').strip()
        if normalize_name(emp_name) in exclude_names:
            continue

        emp_data = df_merged[df_merged['attendance_device_id'] == emp_id]
        if emp_data.empty:
            rows.append((emp_name, '', ''))
            continue

        for _, group in emp_data.sort_values('timestamp').groupby('date', sort=True):
            times = [ts.strftime('%H:%M:%S') for ts in group['timestamp']]
            check_in = times[0] if times else ''
            check_out = times[-1] if len(times) > 1 else ''
            rows.append((emp_name, check_in, check_out))

    atif_row = None
    for idx, row in enumerate(rows):
        if row[0] == 'MUHAMMAD ATIF ZAFAR':
            atif_row = rows.pop(idx)
            break
    if atif_row is not None:
        insert_index = next((i for i, row in enumerate(rows) if row[0] == 'MUHAMMAD ZAFAR HAJI'), len(rows))
        rows.insert(insert_index + 1, atif_row)

    save_daily_checkin_rows(report_start, rows)
    write_consolidated_text_log_from_db()

    print(f"Daily check-in detail log updated in DB and consolidated file: {LOG_TEXT_PATH}")

