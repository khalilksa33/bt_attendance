def get_biometric_data():
    # Calculate previous month for data filtering
    now = datetime.now()
    if now.month == 1:
        prev_month = 12
        prev_year = now.year - 1
    else:
        prev_month = now.month - 1
        prev_year = now.year
    
    # Get first and last day of previous month
    month_start = datetime(prev_year, prev_month, 1)
    month_end = datetime(prev_year, prev_month, calendar.monthrange(prev_year, prev_month)[1], 23, 59, 59)
    
    zk = ZK('192.168.8.4', port=4370, timeout=5)
    conn = zk.connect()
    attendance = conn.get_attendance()
    # Filter for previous month
    filtered_attendance = [{'user_id': record.user_id, 'timestamp': record.timestamp} for record in attendance if month_start <= record.timestamp <= month_end]
    df_biometric = pd.DataFrame(filtered_attendance)
    conn.disconnect()
    return df_biometric

