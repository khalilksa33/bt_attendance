def normalize_whatsapp_number(number):
    normalized = str(number or "").strip()
    if not normalized:
        return ""
    if normalized.startswith("whatsapp:"):
        return normalized
    if normalized.startswith("+"):
        return f"whatsapp:{normalized}"
    if normalized.isdigit():
        return f"whatsapp:+{normalized}"
    return normalized


