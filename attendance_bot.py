        month_start = datetime(year, month_num, 1)
        month_end = datetime(year, month_num, calendar.monthrange(year, month_num)[1], 23, 59, 59)
        df_month = df_merged[(df_merged['timestamp'] >= month_start) & (df_merged['timestamp'] <= month_end)].copy()

        df_month_summary = df_month.groupby('attendance_device_id').apply(calculate_hours).reset_index(name='total_hours')
        df_summary = df_template.merge(df_user_info, on='attendance_device_id', how='left').merge(
            df_month_summary, on='attendance_device_id', how='left')

        df_summary['total_hours'] = df_summary['total_hours'].fillna(0)
        df_summary['employee_name'] = df_summary['attendance_device_id'].map(display_name_map).fillna(df_summary['employee_name'].fillna('N/A'))
        df_summary['department'] = df_summary['department'].fillna('N/A')
        df_summary['designation'] = df_summary['designation'].fillna('N/A')
        df_summary['serial_no'] = df_summary.index + 1
        df_summary['percentage'] = (df_summary['total_hours'] / 216) * 100

