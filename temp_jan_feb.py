def add_timesheet_pages(pdf, df_final, df_merged, month_name):
    for index, row in df_final.iterrows():
        emp_name = row['employee_name']
        emp_device_id = str(row.get('attendance_device_id', ''))
        
        emp_data = df_merged[df_merged['attendance_device_id'] == emp_device_id].copy()
        if emp_data.empty:
            continue
        
        emp_data['date'] = emp_data['timestamp'].dt.date
        emp_data['time'] = emp_data['timestamp'].dt.strftime('%H:%M:%S')
        emp_data = emp_data.sort_values('timestamp')
        
        pdf.add_page('P')
        pdf.set_font("Arial", "B", 12)
        pdf.cell(0, 8, f"Attendance Timesheet - {emp_name}", ln=1, align='C')
        pdf.set_font("Arial", "", 10)
        pdf.cell(0, 6, f"Month: {month_name}", ln=1, align='C')
        pdf.cell(0, 6, f"Designation: {row.get('designation', 'N/A')} | Department: {row.get('department', 'N/A')}", ln=1, align='C')
        pdf.ln(5)

        table_width = 155
        page_width = pdf.w
        left_margin = (page_width - table_width) / 2
        pdf.set_x(left_margin)
        
        pdf.set_line_width(0.5)
        pdf.set_font("Arial", "B", 9)
        pdf.set_fill_color(192, 0, 0)
        pdf.set_text_color(255, 255, 255)
        pdf.cell(15, 8, "S.No", 1, 0, 'C', fill=True)
        pdf.cell(30, 8, "Date", 1, 0, 'C', fill=True)
        pdf.cell(25, 8, "Day", 1, 0, 'C', fill=True)
        pdf.cell(30, 8, "Check-In", 1, 0, 'C', fill=True)
        pdf.cell(30, 8, "Check-Out", 1, 0, 'C', fill=True)
        pdf.cell(25, 8, "Duration", 1, 1, 'C', fill=True)
        
        pdf.set_font("Arial", "", 8)
        pdf.set_text_color(0, 0, 0)
        
        daily_records = emp_data.groupby('date').apply(lambda x: x.sort_values('timestamp')).reset_index(drop=True)
        
        serial_no = 1
        total_days = 0
        total_hours = 0
        for date_val in sorted(emp_data['date'].unique()):
            day_data = emp_data[emp_data['date'] == date_val].sort_values('timestamp')
            day_name = date_val.strftime('%A')
            if len(day_data) >= 2:
                check_in = day_data.iloc[0]['time']
                check_out = day_data.iloc[-1]['time']
                duration_min = (day_data.iloc[-1]['timestamp'] - day_data.iloc[0]['timestamp']).total_seconds() / 60
                duration_hrs = f"{int(duration_min // 60)}:{int(duration_min % 60):02d}"
                total_days += 1
                total_hours += duration_min / 60
            else:
                check_in = day_data.iloc[0]['time'] if len(day_data) > 0 else "N/A"
                check_out = "N/A"
                duration_hrs = "N/A"
            
            pdf.set_x(left_margin)
            pdf.cell(15, 6, str(serial_no), 1, 0, 'C')
            pdf.cell(30, 6, str(date_val), 1, 0, 'C')
            pdf.cell(25, 6, day_name[:3], 1, 0, 'C')  # Short day name
            pdf.cell(30, 6, check_in, 1, 0, 'C')
            pdf.cell(30, 6, check_out, 1, 0, 'C')
            pdf.cell(25, 6, duration_hrs, 1, 1, 'C')
            serial_no += 1
        
        # Summary
        summary = f"Total Days: {total_days}, Total Hours: {total_hours:.1f}"
        pdf.set_font("Arial", "I", 8)
        pdf.cell(0, 6, summary, 0, 1, 'C')

# 4. Email Function
def send_email(filename, month_name):
    msg = MIMEMultipart()
    msg['Subject'] = f'Monthly Attendance Report - {month_name}'
    msg['From'] = os.getenv("EMAIL_USER")
    msg['To'] = os.getenv("RECIPIENT_EMAIL")
    
    with open(filename, "rb") as f:
        attach = MIMEApplication(f.read(), _subtype="pdf")
        attach.add_header('Content-Disposition', 'attachment', filename=Path(filename).name)
        msg.attach(attach)
    
    smtp_server = os.getenv("SMTP_SERVER")
    smtp_port = int(os.getenv("SMTP_PORT"))
    with smtplib.SMTP(smtp_server, smtp_port) as server:
        server.starttls()
        server.login(os.getenv("EMAIL_USER"), email_pass)
        server.send_message(msg)

