# 1. Fetch Biometric Data
def get_biometric_data():
    zk = ZK('192.168.8.4', port=4370, timeout=5)
    conn = zk.connect()
    attendance = conn.get_attendance()
    # Filter for Jan-Mar 2026
    start_date = datetime(2026, 1, 1)
    end_date = datetime(2026, 3, 31, 23, 59, 59)
    filtered_attendance = [{'user_id': record.user_id, 'timestamp': record.timestamp} for record in attendance if start_date <= record.timestamp <= end_date]
    df_biometric = pd.DataFrame(filtered_attendance)
    conn.disconnect()
    return df_biometric

# 2. Fetch ERP User Info
def get_erp_users():
    url = erp_url + '/api/resource/Employee'
    headers = {'Authorization': f'token {api_key}:{os.getenv("ERP_API_SECRET")}'}
    params = {
        'fields': '["employee_name", "attendance_device_id", "department", "designation"]',
        'limit_page_length': 1000
    }
    response = requests.get(url, headers=headers, params=params)
    if response.status_code == 200:
        data = response.json()['data']
        return pd.DataFrame(data)
    else:
        raise Exception(f"ERP API Error: {response.status_code} - {response.text}")

